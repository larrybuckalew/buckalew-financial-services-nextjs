// Utility functions for blog management
export function getAllPosts() {
    return blogPosts.filter(post => post.status === 'published');
}
export function getFeaturedPosts() {
    return blogPosts.filter(post => post.status === 'published' && post.featured);
}
export function getPostBySlug(slug) {
    return blogPosts.find(post => post.slug === slug && post.status === 'published');
}
export function getPostById(id) {
    return blogPosts.find(post => post.id === id && post.status === 'published');
}
export function getPostsByCategory(category) {
    return blogPosts.filter(post => post.status === 'published' &&
        post.category.toLowerCase() === category.toLowerCase());
}
export function getPostsByTag(tag) {
    return blogPosts.filter(post => post.status === 'published' &&
        post.tags.some(postTag => postTag.toLowerCase() === tag.toLowerCase()));
}
export function searchPosts(searchTerm) {
    const term = searchTerm.toLowerCase();
    return blogPosts.filter(post => post.status === 'published' && (post.title.toLowerCase().includes(term) ||
        post.excerpt.toLowerCase().includes(term) ||
        post.content.toLowerCase().includes(term) ||
        post.tags.some(tag => tag.toLowerCase().includes(term)) ||
        post.keywords.some(keyword => keyword.toLowerCase().includes(term))));
}
export function getRelatedPosts(postId, limit = 3) {
    const currentPost = getPostById(postId);
    if (!currentPost)
        return [];
    const related = blogPosts
        .filter(post => post.status === 'published' &&
        post.id !== postId &&
        (post.category === currentPost.category ||
            post.tags.some(tag => currentPost.tags.includes(tag))))
        .slice(0, limit);
    return related;
}
